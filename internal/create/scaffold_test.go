// entry is one node of an instance tree for comparison.
type entry struct {
	kind    string // dir, file, link
	mode    fs.FileMode
	content string
}

func snapshot(t *testing.T, root string, skip ...string) map[string]entry {
	t.Helper()
	out := map[string]entry{}
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(root, path)
		if rel == "." {
			return nil
		}
		rel = filepath.ToSlash(rel)
		for _, s := range skip {
			if rel == s || strings.HasPrefix(rel, s+"/") {
				if d.IsDir() {
					return filepath.SkipDir
				}
				return nil
			}
		}
		info, err := os.Lstat(path)
		if err != nil {
			return err
		}
		switch {
		case info.Mode()&os.ModeSymlink != 0:
			l, _ := os.Readlink(path)
			out[rel] = entry{kind: "link", content: l}
		case info.IsDir():
			out[rel] = entry{kind: "dir", mode: info.Mode().Perm()}
		default:
			data, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			out[rel] = entry{kind: "file", mode: info.Mode().Perm(), content: string(data)}
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return out
}

// Timestamps are the one documented, intended difference: the generated-on
// comment of lolabot.yaml is clock and format dependent (GNU date -Iseconds).
var stampLine = regexp.MustCompile(`(?m)^# Generated by lolabot setup.sh on .*$`)

func normalize(e entry) entry {
	e.content = stampLine.ReplaceAllString(e.content, "# Generated by lolabot setup.sh on <time>")
	return e
}

func compareTrees(t *testing.T, want, got map[string]entry) {
	t.Helper()
	var names []string
	seen := map[string]bool{}
	for k := range want {
		names = append(names, k)
		seen[k] = true
	}
	for k := range got {
		if !seen[k] {
			names = append(names, k)
		}
	}
	sort.Strings(names)
	bad := 0
	for _, n := range names {
		w, wok := want[n]
		g, gok := got[n]
		switch {
		case !wok:
			t.Errorf("only in Go port: %s", n)
		case !gok:
			t.Errorf("only in setup.sh: %s", n)
		default:
			w, g = normalize(w), normalize(g)
			if w.kind != g.kind || w.mode != g.mode || w.content != g.content {
				t.Errorf("%s differs: setup.sh %s %v %q vs Go %s %v %q", n, w.kind, w.mode, abbreviate(w.content), g.kind, g.mode, abbreviate(g.content))
			}
		}
		if t.Failed() {
			if bad++; bad > 15 {
				t.Fatal("too many differences")
			}
		}
	}
}

func abbreviate(s string) string {
	if len(s) > 200 {
		return s[:200] + "..."
	}
	return s
}

func writeFile(t *testing.T, path, body string, mode fs.FileMode) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(body), mode); err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(path, mode); err != nil {
		t.Fatal(err)
	}
}

