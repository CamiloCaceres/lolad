func realTemplate(t *testing.T) string {
	var cands []string
	if v := os.Getenv("LOLAD_TEST_TEMPLATE"); v != "" {
		cands = append(cands, v)
	}
	if home, err := os.UserHomeDir(); err == nil {
		cands = append(cands, filepath.Join(home, "lolabot"))
		if data, err := os.ReadFile(filepath.Join(home, ".config", "lolad", "config.yaml")); err == nil {
			var cfg struct {
				T string `yaml:"lolabot_template"`
			}
			if yaml.Unmarshal(data, &cfg) == nil && cfg.T != "" {
				cands = append(cands, cfg.T)
			}
		}
	}
	for _, c := range cands {
		if _, err := os.Stat(filepath.Join(c, "setup.sh")); err == nil {
			if _, err := os.Stat(filepath.Join(c, "CLAUDE.TEMPLATE.md")); err == nil {
				return c
			}
		}
	}
	t.Skip("real lolabot template unavailable; set LOLAD_TEST_TEMPLATE")
	return ""
}

type fixture struct {
	name, role, user, lang, native string
}

func (f fixture) params(dir string) ScaffoldParams {
	return ScaffoldParams{Name: f.name, Role: f.role, User: f.user, Dir: dir, Language: f.lang, NativeLanguage: f.native,
		SystemName: "test-host", OS: "Darwin", RAM: "16 GB", Storage: "500 GB", Hardware: "Mac14,2", Timezone: "America/Bogota",
		UserEmail: "user@example.com", AgentEmail: "agent@example.com"}
}

// runSetupSh runs the original script, no terminal, with every system fact
// preset through the same variables the script reads.
func runSetupSh(t *testing.T, script string, f fixture, dir string) {
	t.Helper()
	bash, err := exec.LookPath("bash")
	if err != nil {
		t.Skip("bash unavailable")
	}
	if runtime.GOOS == "windows" {
		t.Skip("setup.sh conformance needs a POSIX system")
	}
	stubs := t.TempDir()
	// Keep the optional venv step offline and quick: a failing uv is only a warning.
	writeFile(t, filepath.Join(stubs, "uv"), "#!/bin/sh\nexit 1\n", 0o755)
	env := []string{"HOME=" + t.TempDir(), "PATH=" + stubs + ":/usr/bin:/bin:/usr/sbin:/sbin",
		"SYSTEM_NAME=test-host", "SYSTEM_OS=Darwin", "SYSTEM_RAM=16 GB", "SYSTEM_STORAGE=500 GB", "SYSTEM_HARDWARE=Mac14,2", "SYSTEM_TIMEZONE=America/Bogota"}
	if f.lang != "" {
		env = append(env, "USER_PREFERRED_LANGUAGE="+f.lang)
	}
	if f.native != "" {
		env = append(env, "USER_NATIVE_LANGUAGE="+f.native)
	}
	env, cleanup, err := setupCompatibility(env)
	if err != nil {
		t.Fatal(err)
	}
	defer cleanup()
	cmd := exec.Command(bash, script, "--name", f.name, "--role", f.role, "--user", f.user, "--yes", dir)
	cmd.Env = env
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("setup.sh: %v\n%s", err, out)
	}
}

func conform(t *testing.T, templateDir, script string, f fixture) {
	t.Helper()
	root := t.TempDir()
	shDir := filepath.Join(root, "by-script", "inst")
	goDir := filepath.Join(root, "by-go", "inst")
	// Create makes the directory first; BSD realpath needs it to exist.
	if err := os.MkdirAll(shDir, 0o755); err != nil {
		t.Fatal(err)
	}
	runSetupSh(t, script, f, shDir)
	if err := os.MkdirAll(filepath.Dir(goDir), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := Scaffold(templateDir, f.params(goDir)); err != nil {
		t.Fatal(err)
	}
	// The script also runs `git init` and creates a Python venv when those
	// tools exist. The Go port deliberately does not (documented difference).
	want := snapshot(t, shDir, ".git", ".venv")
	got := snapshot(t, goDir)
	// Absolute locations differ between the two roots: compare with them masked.
	mask := func(m map[string]entry, root string) map[string]entry {
		out := map[string]entry{}
		for k, v := range m {
			v.content = strings.ReplaceAll(v.content, root, "<root>")
			out[k] = v
		}
		return out
	}
	shReal, _ := filepath.EvalSymlinks(filepath.Dir(shDir))
	goReal, _ := filepath.EvalSymlinks(filepath.Dir(goDir))
	compareTrees(t, mask(want, shReal), mask(got, goReal))
}

